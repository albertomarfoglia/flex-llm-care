"""
Generate the experiment configs in reproduction/configs/ (one per model × dataset × variant).

Variants
--------
<model>_<ds>.yaml          main grid: top-3 prompt, greedy decoding (deterministic)
<model>_<ds>_sampled.yaml  Qwen models only: the model's own generation_config (sampling,
                           as in the original code / paper), made repeatable by the seed
<model>_<ds>_top1.yaml     BioMistral only: single-answer prompt (n_output=1), the setting
                           that matches the paper's BioMistral row

Usage: python reproduction/make_configs.py
"""

from pathlib import Path

import yaml

MODELS = {  # key: (HF id, pinned commit)
    "llama-3.3-70b":      ("meta-llama/Llama-3.3-70B-Instruct", "6f6073b423013f6a7d4d9f39144961bfbfbc386b"),
    "med42-70b":          ("m42-health/Llama3-Med42-70B", "867064e18aad7bf3f4795f20dcb25a1108952543"),
    "falcon-40b":         ("tiiuae/falcon-40b-instruct", "ecb78d97ac356d098e79f0db222c9ce7c5d9ee5f"),
    "biomistral-7b-dare": ("BioMistral/BioMistral-7B-DARE", "588fca722fbffc46eab97cbe610d4203f303add8"),
    "qwen-umls-7b":       ("prithivMLmods/Qwen-UMLS-7B-Instruct", "3aa922654cfc6aec0c94f1b9e6f4faabb38b15ad"),
    "qwen2.5-72b":        ("Qwen/Qwen2.5-72B-Instruct", "495f39366efef23836d0cfae4fbe635880d2be31"),
}
DATASETS = {"motu": "motu_enriched.csv", "mimic": "mimic_enriched.csv", "sphn": "sphn/sphn.csv"}
SAMPLED = ("qwen-umls-7b", "qwen2.5-72b")
TOP1 = ("biomistral-7b-dare",)


def make(model: str, revision: str, dataset: str, decoding: str = "greedy",
         n_output: int = 3, prompt: str = "prompt_top_3.txt") -> dict:
    """Return one config dict."""
    return {
        "project_name": "FHIR Classification",
        "experiment_name": "reproduction",
        "run_id": None,
        "seed": 42,
        "dataset": {"name": dataset},
        "retrieval": {
            "embeddings": "abhinand/MedEmbed-large-v0.1",
            "embeddings_revision": "963121bfb9c625475f65b08fb54990ce9c4e7a1a",
            "k": 6,
            "every_represented_candidate": True,
            "chunk_size": 6,
            "index_path": "models/faiss_index",
        },
        "model": {
            "name": model,
            "revision": revision,
            "n_output": n_output,
            "prompt_template": f"references/configs/prompts/{prompt}",
            "decoding": decoding,
            "max_new_tokens": 50,
            "cache_dir": None,
        },
    }


def main() -> None:
    """Write all configs."""
    out = Path(__file__).resolve().parent / "configs"
    out.mkdir(exist_ok=True)
    written = 0
    for key, (model, rev) in MODELS.items():
        for ds_key, ds in DATASETS.items():
            variants = {"": make(model, rev, ds)}
            if key in SAMPLED:
                variants["_sampled"] = make(model, rev, ds, decoding="model_default")
            if key in TOP1:
                variants["_top1"] = make(model, rev, ds, n_output=1, prompt="prompt.txt")
            for suffix, cfg in variants.items():
                cfg["run_id"] = f"{key}_{ds_key}{suffix}"
                (out / f"{key}_{ds_key}{suffix}.yaml").write_text(
                    "# Generated by reproduction/make_configs.py — do not edit by hand.\n"
                    + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
                written += 1
    print(f"wrote {written} configs to {out}")


if __name__ == "__main__":
    main()
