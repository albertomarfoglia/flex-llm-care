"""
Generate the configurations of the ablation, energy and promotion experiments of the paper
in reproduction/configs_revision/. Each variant changes exactly one factor of the
reference configuration (reproduction/make_configs.py).

Run ids: <model>_<dataset>_<variant>
  ref         reference configuration, re-run with energy and token instrumentation
              (Sections 5.9-5.10); on motu_original / mimic_original: original,
              non-enriched descriptions (Section 5.7)
  norag       no retrieval, all 65 resources listed (prompt_top_3_norag.txt)
  free        unconstrained generation (JSON parsed afterwards)
  k3/k10/k15  number of retrieved candidates
  pubmedbert  NeuML/pubmedbert-base-embeddings retriever (also the candidate of the
              promotion step, Section 5.10)
  chat        native chat format (prompt_top_3_chat.txt, model's own template once)
  eosfix      Med42 only, MOTU+SPHN: reference configuration + stop at the tokenizer EOS,
              to test whether Med42's runtime is due to its generation_config EOS (Section 5.9)

Usage: python reproduction/make_revision_configs.py
"""

from pathlib import Path

import yaml

from make_configs import MODELS, make  # pylint: disable=import-error

DATASETS = {"motu": "motu_enriched.csv", "mimic": "mimic_enriched.csv", "sphn": "sphn/sphn.csv"}
ORIGINAL = {"motu_original": "motu/motu.csv", "mimic_original": "mimic/mimic.csv"}
PUBMEDBERT = ("NeuML/pubmedbert-base-embeddings", "d6eaca8254bc229f3ca42749a5510ae287eb3486",
              "models/faiss_index_pubmedbert")

E1_E2_MODELS = ("qwen2.5-72b", "llama-3.3-70b", "qwen-umls-7b")
E3_MODELS    = ("qwen2.5-72b", "qwen-umls-7b")
E4_MODELS    = ("qwen2.5-72b",)
E5_MODELS    = ("qwen2.5-72b", "llama-3.3-70b", "med42-70b")
E8_MODELS    = tuple(MODELS)


def variants(key: str, model: str, rev: str) -> dict[str, dict]:
    """All revision configs of one model, keyed by run id."""
    out = {}
    if key in E5_MODELS:
        for ds_key, ds in DATASETS.items():
            out[f"{key}_{ds_key}_ref"] = make(model, rev, ds)
    if key == "med42-70b":
        for ds_key in ("motu", "sphn"):
            cfg = make(model, rev, DATASETS[ds_key])
            cfg["model"]["stop_on_tokenizer_eos"] = True
            out[f"{key}_{ds_key}_eosfix"] = cfg
    if key in E1_E2_MODELS:
        for ds_key, ds in ORIGINAL.items():
            out[f"{key}_{ds_key}_ref"] = make(model, rev, ds)
        for ds_key, ds in DATASETS.items():
            cfg = make(model, rev, ds, prompt="prompt_top_3_norag.txt")
            cfg["retrieval"]["mode"] = "none"
            out[f"{key}_{ds_key}_norag"] = cfg
    for ds_key, ds in DATASETS.items():
        if key in E3_MODELS:
            cfg = make(model, rev, ds)
            cfg["model"]["constrained"] = False
            out[f"{key}_{ds_key}_free"] = cfg
        if key in E4_MODELS:
            for k in (3, 10, 15):
                cfg = make(model, rev, ds)
                cfg["retrieval"]["k"] = k
                out[f"{key}_{ds_key}_k{k}"] = cfg
            cfg = make(model, rev, ds)
            cfg["retrieval"].update(embeddings=PUBMEDBERT[0], embeddings_revision=PUBMEDBERT[1],
                                    index_path=PUBMEDBERT[2])
            out[f"{key}_{ds_key}_pubmedbert"] = cfg
        if key in E8_MODELS:
            cfg = make(model, rev, ds, prompt="prompt_top_3_chat.txt")
            cfg["model"]["prompt_format"] = "chat"
            out[f"{key}_{ds_key}_chat"] = cfg
    return out


def main() -> None:
    """Write all revision configs."""
    out = Path(__file__).resolve().parent / "configs_revision"
    out.mkdir(exist_ok=True)
    written = 0
    for key, (model, rev) in MODELS.items():
        for run_id, cfg in variants(key, model, rev).items():
            cfg["run_id"] = run_id
            cfg["experiment_name"] = "revision"
            (out / f"{run_id}.yaml").write_text(
                "# Generated by reproduction/make_revision_configs.py — do not edit by hand.\n"
                + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
            written += 1
    print(f"wrote {written} configs to {out}")


if __name__ == "__main__":
    main()
